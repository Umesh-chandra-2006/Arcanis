async function seedSpells() {
  console.log("Seeding 36 platform base spells...");

  for (const spellData of platformSpells) {
    const spellId = nanoid(36);

    await db.insert(spells).values({
      id: spellId,
      ownerId: undefined,
      name: spellData.name,
      element: spellData.element,
      tier: spellData.tier,
      primaryCategory: spellData.primaryCategory,
      secondaryCategory: null,
      castType: spellData.castType,
      castTimeMs: spellData.castTimeMs,
      damageMin: spellData.damageMin,
      damageMax: spellData.damageMax,
      mpCost: spellData.mpCost,
      mpMaintenancePerTurn: spellData.mpMaintenancePerTurn || null,
      willCostMin: spellData.willCostMin,
      willCostMax: spellData.willCostMax,
      willDrainPerTurn: spellData.willDrainPerTurn || null,
      interruptionThreshold: spellData.interruptionThreshold || null,
      scalingFactor: null,
      mpModifier: null,
      isPhysical: false,
      physicalDelivery: null,
      trapCondition: null,
      trapVisibility: null,
      flavorText: spellData.flavorText,
      loreLine: spellData.loreLine,
      imageUrl: null,
      isPlatformSpell: true,
      researchStatus: "ready",
      researchStartedAt: null,
      researchComplexityScore: null,
    });

    console.log(`✓ Seeded: ${spellData.name}`);
  }

  console.log("✅ All 36 platform spells seeded successfully!");
}

seedSpells().catch(console.error);
